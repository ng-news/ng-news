#!/usr/bin/env node
/**
 * Build-time content generator.
 *
 * Reads content/index.json plus any Markdown issue files referenced by
 * "file" (e.g. 26-01.md) and emits a TypeScript module into the app:
 *
 *   app/src/app/generated/content.generated.ts
 *
 * The generated module is the ONLY data the app sees — no runtime HTTP.
 *
 * Usage: node content/build-content.mjs   (also runs via pnpm prebuild)
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, '../app/src/app/generated/content.generated.ts');

// ---------------------------------------------------------------------------
// Minimal Markdown -> HTML (the subset used by ng-news drafts)
// ---------------------------------------------------------------------------
function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function inline(s) {
  let t = escapeHtml(s);
  t = t.replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g, '<a href="$2" rel="noopener" target="_blank">$1</a>');
  t = t.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  t = t.replace(/`([^`]+)`/g, '<code>$1</code>');
  return t;
}

function markdownToHtml(md) {
  const lines = md.replace(/\r\n/g, '\n').split('\n');
  const out = [];
  let para = [];
  let list = [];

  const flushPara = () => {
    if (para.length) out.push(`<p>${inline(para.join(' '))}</p>`);
    para = [];
  };
  const flushList = () => {
    if (list.length) out.push(`<ul>${list.map((li) => `<li>${inline(li)}</li>`).join('')}</ul>`);
    list = [];
  };

  for (const raw of lines) {
    const line = raw.trimEnd();
    const h = line.match(/^(#{1,4})\s+(.*)$/);
    if (h) {
      // The editorial appendix (fact-check results) never ships to the site.
      if (/^#\s*Fact Check/i.test(line)) break;
      flushPara();
      flushList();
      const level = h[1].length;
      out.push(`<h${level}>${inline(h[2])}</h${level}>`);
      continue;
    }
    if (/^---+$/.test(line.trim())) {
      flushPara();
      flushList();
      out.push('<hr>');
      continue;
    }
    const li = line.match(/^[-*]\s+(.*)$/);
    if (li) {
      flushPara();
      list.push(li[1]);
      continue;
    }
    if (line.trim() === '') {
      flushPara();
      flushList();
      continue;
    }
    flushList();
    para.push(line.trim());
  }
  flushPara();
  flushList();
  return out.join('\n');
}

// ---------------------------------------------------------------------------
// Assemble issues
// ---------------------------------------------------------------------------
const index = JSON.parse(readFileSync(join(here, 'index.json'), 'utf8'));
const files = readdirSync(here).filter((f) => f.endsWith('.md'));

const issues = index.issues.map(({ file, ...issue }) => {
  if (file) {
    const mdFile = join(here, file);
    if (!files.includes(file)) {
      throw new Error(`Issue ${issue.id}: missing markdown file content/${file}`);
    }
    const html = markdownToHtml(readFileSync(mdFile, 'utf8'));
    return { ...issue, bodyHtml: html };
  }
  return issue;
});

// ---------------------------------------------------------------------------
// Emit TypeScript module
// ---------------------------------------------------------------------------
const ts = `/**
 * GENERATED FILE — do not edit by hand.
 *
 * Generated by content/build-content.mjs from:
 *   content/index.json
 *   ${files.join(', ') || '(no markdown files)'}
 *
 * Regenerate with: pnpm content:build  (runs automatically before pnpm build)
 */
import { Issue, LatestVideo, SiteMeta } from '../core/issue.model';

export const SITE: SiteMeta = ${JSON.stringify(index.site, null, 2)};

export const LATEST_VIDEO: LatestVideo = ${JSON.stringify(index.latestVideo, null, 2)};

export const ISSUES: Issue[] = ${JSON.stringify(issues, null, 2)};
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, ts);

// ---------------------------------------------------------------------------
// Emit the search index (client-side full-text search, MiniSearch).
// One doc per issue + one per topic. Fetched once at runtime from
// /search-index.json and indexed in the browser — no search backend needed.
// ---------------------------------------------------------------------------
const searchDocs = [];
for (const issue of issues) {
  const url = `/issues/${issue.id.slice(0, 2)}/${issue.id.slice(3)}`;
  searchDocs.push({
    id: `issue-${issue.id}`,
    type: 'issue',
    title: `${issue.id} — ${issue.title}`,
    url,
    tags: issue.tags,
    text: [issue.title, issue.teaser, ...issue.topics.map((t) => t.title)].join(' '),
  });
  issue.topics.forEach((t, i) => {
    searchDocs.push({
      id: `topic-${issue.id}-${i}`,
      type: 'topic',
      title: t.title,
      url,
      tags: t.tag ? [t.tag] : [],
      text: `${issue.id} ${issue.title} ${t.title}`,
    });
  });
}
const searchIndexPath = resolve(here, '../app/public/search-index.json');
writeFileSync(searchIndexPath, JSON.stringify({ version: 1, docs: searchDocs }));

const withBody = issues.filter((i) => i.bodyHtml).map((i) => i.id);
console.log(`[content] wrote ${outPath}`);
console.log(`[content] ${issues.length} issues, full text for: ${withBody.join(', ') || '(none)'}`);
console.log(`[content] wrote ${searchIndexPath} (${searchDocs.length} docs)`);
